@ Updates patch: invisible walls along a course's track (new design, not Rare's).
@ Written for this project. Each course with walls has a 64x64 grid of 16-unit cells
@ (generated by tools/course_build.py from the course's racing line): 0 for a cell on
@ the track, else 0x80 | the direction back to the track in 128ths of a turn. Once a
@ race is under way (sys_flags bit 2, set at GO, the same flag the start hoop's lap
@ check uses), a plane that leaves the track is pushed back onto it; the player's
@ plane also bounces the way Rare's planes bounce off the edge of the world
@ (move_player, plane.c:229-265): turned, knocked back for a moment, and the wall
@ sound. Before GO the planes fly in
@ from off the track, so the walls aren't up yet.
@ Called every frame from fix_df_positions_far (the race monitor's per-frame hook,
@ updates/code/dogfight.s). Keeps r4-r7.

	.section .fixes, "ax", %progbits
	.thumb
	.balign 2

	.equ	SYS_RACING, 4			@ sys_flags: race under way (from GO)
	.equ	O_TYPE, 2			@ 1 the player's plane
	.equ	O_X, 32				@ position, 8.8 fixed point
	.equ	O_Z, 40
	.equ	O_SPIN, 56			@ the bounce's spin
	.equ	O_HEADING, 60
	.equ	O_TURN, 64
	.equ	O_FLAGS, 80
	.equ	O_STATE, 120			@ nonzero: bouncing, tumbling... (not steering)
	.equ	SFX_WALL, 53			@ the sound move_player plays at the world's edge

	.thumb_func
course_walls:
	push	{r4, r5, r6, r7, lr}
	ldr	r0, =sys_flags
	ldr	r0, [r0, #0]
	movs	r1, #SYS_RACING
	tst	r0, r1
	beq	9f
	ldr	r0, =game_level
	ldr	r0, [r0, #0]
	adr	r1, course_wall_grids
1:	ldr	r2, [r1, #0]
	cmp	r2, #0
	beq	9f				@ no walls on this course
	cmp	r2, r0
	beq	2f
	adds	r1, #8
	b	1b
2:	ldr	r7, [r1, #4]			@ r7 = the grid
	movs	r6, #0				@ player number
3:	ldr	r0, =players
	lsls	r1, r6, #2
	ldr	r4, [r0, r1]
	cmp	r4, #0
	beq	5f
	ldr	r0, [r4, #O_STATE]
	cmp	r0, #0
	bne	5f				@ already bouncing or tumbling
	ldr	r0, [r4, #O_X]
	bl	wall_cell
	adds	r5, r0, #0
	ldr	r0, [r4, #O_Z]
	bl	wall_cell
	lsls	r0, r0, #6
	adds	r0, r0, r5
	ldrb	r5, [r7, r0]
	lsls	r0, r5, #24
	bpl	5f				@ on the track
	lsls	r5, r5, #25			@ direction back to the track
	lsrs	r5, r5, #16			@ as a 16-bit heading
	bl	wall_bounce
5:	adds	r6, #1
	cmp	r6, #3
	ble	3b
9:	pop	{r4, r5, r6, r7}
	pop	{r0}
	bx	r0

@ r0 = a position (8.8) -> its cell, 0-63
wall_cell:
	asrs	r0, r0, #12
	bpl	1f
	movs	r0, #0
1:	cmp	r0, #63
	ble	2f
	movs	r0, #63
2:	bx	lr

@ r4 = the plane, r5 = the heading back to the track. It's put 8 units back towards
@ the track (more than a plane flies in a frame, so it slides along the wall). A
@ computer plane gets only that, so it keeps flying its route. The player's plane
@ also bounces as move_player does at the world's edge: with flags bit 0 it just
@ turns back, otherwise it's knocked back facing the wall and spun round (state 3),
@ with the wall sound.
wall_bounce:
	push	{lr}
	ldr	r1, =D_083e35d8			@ sin
	ldr	r1, [r1, #0]
	adds	r0, r5, #0
	bl	wall_bx_r1
	lsls	r0, r0, #16
	asrs	r0, r0, #17			@ 8 units, in 8.8
	ldr	r1, [r4, #O_X]
	adds	r1, r1, r0
	str	r1, [r4, #O_X]
	ldr	r1, =D_083e35dc			@ cos
	ldr	r1, [r1, #0]
	adds	r0, r5, #0
	bl	wall_bx_r1
	lsls	r0, r0, #16
	asrs	r0, r0, #17
	ldr	r1, [r4, #O_Z]
	adds	r1, r1, r0
	str	r1, [r4, #O_Z]
	ldrh	r0, [r4, #O_TYPE]
	cmp	r0, #1
	bne	9f				@ a computer plane is only slid back, so it keeps its line
	ldr	r1, [r4, #O_FLAGS]
	movs	r2, #1
	tst	r1, r2
	beq	1f
	str	r5, [r4, #O_HEADING]		@ face the track
	b	9f
1:	movs	r0, #128			@ facing the wall, knocked back from it
	lsls	r0, r0, #8
	eors	r0, r5
	str	r0, [r4, #O_HEADING]
	movs	r0, #128
	lsls	r0, r0, #7			@ 0x4000
	orrs	r1, r0
	ldr	r0, =0xfffffeff
	ands	r1, r0
	str	r1, [r4, #O_FLAGS]
	movs	r0, #224
	lsls	r0, r0, #8			@ 0xe000
	str	r0, [r4, #O_SPIN]
	movs	r0, #3
	str	r0, [r4, #O_STATE]
	movs	r0, #0
	str	r0, [r4, #O_TURN]
	ldrh	r0, [r4, #O_TYPE]
	cmp	r0, #1
	bne	9f
	movs	r0, #SFX_WALL
	movs	r1, #127
	movs	r2, #128
	lsls	r2, r2, #10
	ldr	r3, =audio_new_fx+1
	bl	wall_bx_r3
9:	pop	{r0}
	bx	r0
wall_bx_r3:
	bx	r3
wall_bx_r1:
	bx	r1
	.ltorg

	.balign 4				@ adr needs a word-aligned table
@ game_level, its wall grid (from the course's generated .s); 0 ends the table
course_wall_grids:
	.word	37, walls_temple_tangle		@ Temple Tangle
	.word	0
	.balign 4
