@ Updates patch: invisible walls along a course's track (new design, not Rare's).
@ Written for this project. Each course with walls has a 64x64 grid of 16-unit cells
@ (generated by tools/course_build.py from the course's racing line): 0 for a cell on
@ the track, else 0x80 | the direction back to the track in 128ths of a turn. Once a
@ race is under way (sys_flags bit 2, set at GO, the same flag the start hoop's lap
@ check uses), a plane that leaves the track is pushed back onto it; the player's
@ plane also stops dead, like hitting a tree but without being knocked down. Before GO the planes fly in
@ from off the track, so the walls aren't up yet.
@ Called every frame from fix_df_positions_far (the race monitor's per-frame hook,
@ updates/code/dogfight.s). Keeps r4-r7.

	.section .fixes, "ax", %progbits
	.thumb
	.balign 2

	.equ	SYS_RACING, 4			@ sys_flags: race under way (from GO)
	.equ	O_TYPE, 2			@ 1 the player's plane
	.equ	O_X, 32				@ position, 8.8 fixed point
	.equ	O_Z, 40
	.equ	O_VX, 44			@ velocity (rebuilt from heading and speed each frame)
	.equ	O_VZ, 52
	.equ	O_SPEED, 104
	.equ	WALL_SOUND_SPEED, 256		@ speed below which touching the wall is silent
	.equ	O_STATE, 120			@ nonzero: bouncing, tumbling... (not steering)
	.equ	SFX_WALL, 53			@ the sound move_player plays at the world's edge

	.thumb_func
course_walls:
	push	{r4, r5, r6, r7, lr}
	ldr	r0, =sys_flags
	ldr	r0, [r0, #0]
	movs	r1, #SYS_RACING
	tst	r0, r1
	beq	9f
	ldr	r0, =game_level
	ldr	r0, [r0, #0]
	adr	r1, course_wall_grids
1:	ldr	r2, [r1, #0]
	cmp	r2, #0
	beq	9f				@ no walls on this course
	cmp	r2, r0
	beq	2f
	adds	r1, #8
	b	1b
2:	ldr	r7, [r1, #4]			@ r7 = the grid
	movs	r6, #0				@ player number
3:	ldr	r0, =players
	lsls	r1, r6, #2
	ldr	r4, [r0, r1]
	cmp	r4, #0
	beq	5f
	ldr	r0, [r4, #O_STATE]
	cmp	r0, #0
	bne	5f				@ already bouncing or tumbling
	ldr	r0, [r4, #O_X]
	bl	wall_cell
	adds	r5, r0, #0
	ldr	r0, [r4, #O_Z]
	bl	wall_cell
	lsls	r0, r0, #6
	adds	r0, r0, r5
	ldrb	r5, [r7, r0]
	lsls	r0, r5, #24
	bpl	5f				@ on the track
	lsls	r5, r5, #25			@ direction back to the track
	lsrs	r5, r5, #16			@ as a 16-bit heading
	bl	wall_bounce
5:	adds	r6, #1
	cmp	r6, #3
	ble	3b
9:	pop	{r4, r5, r6, r7}
	pop	{r0}
	bx	r0

@ r0 = a position (8.8) -> its cell, 0-63
wall_cell:
	asrs	r0, r0, #12
	bpl	1f
	movs	r0, #0
1:	cmp	r0, #63
	ble	2f
	movs	r0, #63
2:	bx	lr

@ r4 = the plane, r5 = the heading back to the track. It's put 8 units back towards
@ the track (more than a plane flies in a frame). A computer plane gets only that, so
@ it slides along the wall and keeps flying its route. The player's plane also comes
@ to a halt, as on flying into a tree (player_collide) but without the knock-down
@ (no hit state): speed and velocity to 0, heading unchanged; the wall sound plays
@ if it hit at speed.
wall_bounce:
	push	{lr}
	ldr	r1, =D_083e35d8			@ sin
	ldr	r1, [r1, #0]
	adds	r0, r5, #0
	bl	wall_bx_r1
	lsls	r0, r0, #16
	asrs	r0, r0, #17			@ 8 units, in 8.8
	ldr	r1, [r4, #O_X]
	adds	r1, r1, r0
	str	r1, [r4, #O_X]
	ldr	r1, =D_083e35dc			@ cos
	ldr	r1, [r1, #0]
	adds	r0, r5, #0
	bl	wall_bx_r1
	lsls	r0, r0, #16
	asrs	r0, r0, #17
	ldr	r1, [r4, #O_Z]
	adds	r1, r1, r0
	str	r1, [r4, #O_Z]
	ldrh	r0, [r4, #O_TYPE]
	cmp	r0, #1
	bne	9f				@ a computer plane is only slid back, so it keeps its line
	ldr	r1, [r4, #O_SPEED]		@ the player's plane stops dead, as on hitting
	movs	r0, #0				@ a tree, but without being knocked down
	str	r0, [r4, #O_SPEED]
	str	r0, [r4, #O_VX]
	str	r0, [r4, #O_VZ]
	ldr	r0, =WALL_SOUND_SPEED
	cmp	r1, r0				@ the wall sound only for a real hit, not for
	blt	9f				@ every frame spent nosing against it
	movs	r0, #SFX_WALL
	movs	r1, #127
	movs	r2, #128
	lsls	r2, r2, #10
	ldr	r3, =audio_new_fx+1
	bl	wall_bx_r3
9:	pop	{r0}
	bx	r0
wall_bx_r3:
	bx	r3
wall_bx_r1:
	bx	r1
	.ltorg

	.balign 4				@ adr needs a word-aligned table
@ game_level, its wall grid (from the course's generated .s); 0 ends the table
course_wall_grids:
	.word	37, walls_temple_tangle		@ Temple Tangle
	.word	2, walls_beach_01		@ updates/courses/rare/beach_01.py
	.word	1, walls_beach_00		@ updates/courses/rare/beach_00.py
	.word	5, walls_lava_00		@ updates/courses/rare/lava_00.py
	.word	8, walls_snow_00		@ updates/courses/rare/snow_00.py
	.word	20, walls_farm_00		@ updates/courses/rare/farm_00.py
	.word	30, walls_haunted_00		@ updates/courses/rare/haunted_00.py
	.word	0
	.balign 4
